# Project #74: Inventory Reversing System

# 1. Setup a list of itemsadded over time (oldest to newest)
loot_history = ["🪵 Stick", "⚔️ Sword", "🗡️ Dagger","Steel Sword", "👑 Golden Crown"]

print("📜 Quest History (Oldest -> Newest):")
print(loot_history)

# 2.Reverse the list order
loot_history.reverse()

print("\n⚡️ Reversing list order....")

# 3.Print the reversed history(newest to oldest)
print("📜 Recent Achievements (Newest -> Oldest):")
print(loot_history)
