# Project #73: Weapon Power Analyzer

# 1. Setup a list of weapon damage values
weapon_powers = [12, 42, 8, 95, 23]

print("⚔️ Weapon Power Levels:" + str(weapon_powers))

# 2.Find the maximum (strongest)value in the list 
strongest_weapon = max(weapon_powers)

# 3.Find the minimum (weakest)value in the list
weakest_weapon = min(weapon_powers)

print("\n📊. Equipment Analysis:")
print("💥 Highest Damage Value:" + str(strongest_weapon))
print("🪵 Lowest Damage Value:" + str(weakest_weapon))
